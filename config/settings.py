def _load_env(path):
    """Lit le fichier .env (CLE=valeur, une par ligne). Les vraies variables d'environnement
    restent prioritaires. Ce fichier contient des secrets : il ne doit jamais aller sur GitHub."""
    import os
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


_load_env(BASE_DIR / ".env")


